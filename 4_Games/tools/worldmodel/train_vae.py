"""Trains Gaslight's world model: a small conditional VAE that turns a
creature's species and a random code into a variant - its three colours and
its size - and exports the decoder to Gaslight/GLWorld.h.

The training set is made by hand-tuned palette rules (harmonious hue turns,
keep the contrast between body and belly, an occasional bold accent, rare
pale "Storied" variants). The VAE learns that distribution, so on the console
one small decode per creature gives a variant that looks like it belongs.

usage: python train_vae.py ../../Gaslight/Dex.cpp ../../Gaslight/GLWorld.h
"""
import colorsys
import random
import re
import sys
import numpy as np
import torch
import torch.nn as nn

Z, HID = 6, 64


def species_colours(dex_path):
    """(c1, c2, c3, size, t1, t2) for each species, read from Dex.cpp."""
    src = open(dex_path).read()
    out = []
    for m in re.finditer(r'\{"(\w+)", (T_\w+), (T_\w+|TN),.*?\n\s*\{(\d), (\d), (\d), (\d), (\d), (\d), (0x[0-9A-F]+), (0x[0-9A-F]+), (0x[0-9A-F]+), ([\d.]+)f\}', src):
        cols = [int(m.group(i), 16) for i in (10, 11, 12)]
        out.append((m.group(1), cols, float(m.group(13))))
    return out


def rgb(c):
    return [((c >> 16) & 255) / 255, ((c >> 8) & 255) / 255, (c & 255) / 255]


def cond_of(cols, size):
    v = []
    for c in cols:
        v += rgb(c)
    return v + [size / 1.5]


def variant(cols, size, rnd):
    """One plausible variant by the palette rules."""
    turn = rnd.gauss(0, 0.045)
    sat = rnd.gauss(1, 0.12)
    val = rnd.gauss(1, 0.08)
    storied = rnd.random() < 0.03
    out = []
    for i, c in enumerate(cols):
        h, s, v = colorsys.rgb_to_hsv(*rgb(c))
        h = (h + turn * (1.4 if i == 2 else 1)) % 1
        s = min(1, max(0, s * sat))
        v = min(1, max(0, v * val))
        if storied:
            s *= 0.35
            v = min(1, v * 1.25 + 0.15)
        if i == 2 and rnd.random() < 0.15:  # a bold accent
            h = (h + 0.5) % 1
        out += list(colorsys.hsv_to_rgb(h, s, v))
    out.append(min(1.15, max(0.85, rnd.gauss(1, 0.05))))
    return out


class CVAE(nn.Module):
    def __init__(self, nc, nx):
        super().__init__()
        self.enc = nn.Sequential(nn.Linear(nc + nx, HID), nn.Tanh(), nn.Linear(HID, 2 * Z))
        self.dec = nn.Sequential(nn.Linear(nc + Z, HID), nn.Tanh(), nn.Linear(HID, HID), nn.Tanh(), nn.Linear(HID, nx))

    def forward(self, c, x):
        mu, lv = self.enc(torch.cat([c, x], 1)).chunk(2, 1)
        z = mu + torch.randn_like(mu) * torch.exp(0.5 * lv)
        return self.dec(torch.cat([c, z], 1)), mu, lv


def carr(name, a):
    flat = np.asarray(a, dtype=np.float32).flatten()
    return "static const float %s[%d] = {%s};" % (name, len(flat), ",".join("%.6gf" % v for v in flat))


def main(dex, out):
    sp = species_colours(dex)
    print(len(sp), "species")
    rnd = random.Random(3)
    C, X = [], []
    for name, cols, size in sp:
        c = cond_of(cols, size)
        for _ in range(400):
            C.append(c)
            X.append(variant(cols, size, rnd))
    C = torch.tensor(C, dtype=torch.float32)
    X = torch.tensor(X, dtype=torch.float32)
    torch.manual_seed(1)
    net = CVAE(C.shape[1], X.shape[1])
    opt = torch.optim.Adam(net.parameters(), lr=2e-3)
    for step in range(6000):
        idx = torch.randint(0, len(C), (256,))
        xr, mu, lv = net(C[idx], X[idx])
        rec = ((xr - X[idx]) ** 2).sum(1).mean()
        kl = (-0.5 * (1 + lv - mu ** 2 - lv.exp()).sum(1)).mean()
        loss = rec + 0.02 * kl
        opt.zero_grad(); loss.backward(); opt.step()
        if step % 1000 == 0:
            print("step", step, "rec %.4f kl %.3f" % (rec.item(), kl.item()))
    d = net.dec
    W1, b1 = d[0].weight.detach().numpy(), d[0].bias.detach().numpy()
    W2, b2 = d[2].weight.detach().numpy(), d[2].bias.detach().numpy()
    W3, b3 = d[4].weight.detach().numpy(), d[4].bias.detach().numpy()
    n = sum(a.size for a in (W1, b1, W2, b2, W3, b3))
    print("decoder parameters", n)
    L = ["#pragma once", "", "// Gaslight's world model: the decoder of a conditional VAE that makes",
         "// creature variants (three colours and a size) from a species and a code.",
         "// Generated by tools/worldmodel/train_vae.py - don't edit.", "",
         "namespace Gaslight {",
         "static const int WM_Z = %d, WM_C = %d, WM_H = %d, WM_X = %d;" % (Z, C.shape[1], HID, X.shape[1]),
         carr("WM_W1", W1), carr("WM_B1", b1), carr("WM_W2", W2), carr("WM_B2", b2), carr("WM_W3", W3), carr("WM_B3", b3),
         "} // namespace Gaslight", ""]
    open(out, "w", newline="\n").write("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
