"""Trains Gaslight's chatter model and exports it to Gaslight/GLText.h.

A character-level GRU: embedding 32 -> one GRU layer of 160 -> characters.
Quantised to int8 with a scale per row. The input side of the GRU is folded
into a table (one row per character), so the console only does the
hidden-to-hidden multiply each step.

usage: python train.py corpus.txt ../../Gaslight/GLText.h [minutes]
"""
import math
import sys
import time
import numpy as np
import torch
import torch.nn as nn

H, E = 160, 32
SEQ = 96


def load(path):
    text = open(path).read()
    chars = sorted(set(text))
    return text, chars


class Net(nn.Module):
    def __init__(self, v):
        super().__init__()
        self.emb = nn.Embedding(v, E)
        self.gru = nn.GRU(E, H, batch_first=True)
        self.out = nn.Linear(H, v)

    def forward(self, x, h=None):
        y, h = self.gru(self.emb(x), h)
        return self.out(y), h


def q8(w):
    """int8 per row, returns (q, scale)."""
    w = np.asarray(w, dtype=np.float32)
    s = np.abs(w).max(axis=1) / 127.0 + 1e-9
    q = np.clip(np.round(w / s[:, None]), -127, 127).astype(np.int8)
    return q, s.astype(np.float32)


def carr(name, a, ctype):
    flat = a.flatten()
    body = ",".join(str(int(v)) if "int" in ctype else ("%.7gf" % v) for v in flat)
    lines = []
    for i in range(0, len(body), 2000):
        j = body.rfind(",", 0, i + 2000) if i + 2000 < len(body) else len(body)
        lines.append(body[i:j])
    # rejoin cleanly (rfind split keeps commas consistent)
    return "static const %s %s[%d] = {%s};" % (ctype, name, len(flat), body)


def main(corpus, out, minutes):
    text, chars = load(corpus)
    stoi = {c: i for i, c in enumerate(chars)}
    data = torch.tensor([stoi[c] for c in text], dtype=torch.long)
    v = len(chars)
    torch.manual_seed(1)
    net = Net(v)
    opt = torch.optim.Adam(net.parameters(), lr=3e-3)
    lossf = nn.CrossEntropyLoss()
    t0, step = time.time(), 0
    n = len(data) - SEQ - 1
    while time.time() - t0 < minutes * 60:
        idx = torch.randint(0, n, (64,))
        x = torch.stack([data[i:i + SEQ] for i in idx])
        y = torch.stack([data[i + 1:i + SEQ + 1] for i in idx])
        logits, _ = net(x)
        loss = lossf(logits.reshape(-1, v), y.reshape(-1))
        opt.zero_grad()
        loss.backward()
        nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step()
        step += 1
        if step % 200 == 0:
            print("step %d loss %.3f (%.0fs)" % (step, loss.item(), time.time() - t0))
        if step == 3000:
            for g in opt.param_groups:
                g["lr"] = 1e-3
    print("params", sum(p.numel() for p in net.parameters()))
    # samples, to check by eye
    net.eval()
    for tag in ("<fc>", "<sc>", "<kc>", "<ur>", "<ab>"):
        with torch.no_grad():
            h = None
            s = tag
            x = torch.tensor([[stoi[c] for c in tag]])
            o, h = net(x)
            for _ in range(100):
                p = torch.softmax(o[0, -1] / 0.7, -1)
                c = torch.multinomial(p, 1).item()
                if chars[c] == "\n":
                    break
                s += chars[c]
                o, h = net(torch.tensor([[c]]), h)
        print("sample:", s)
    # export: the input side folded per character, the rest int8
    sd = {k: val.detach().numpy() for k, val in net.state_dict().items()}
    emb = sd["emb.weight"]                      # v x E
    Wih, Whh = sd["gru.weight_ih_l0"], sd["gru.weight_hh_l0"]   # 3H x E, 3H x H (r, z, n)
    bih, bhh = sd["gru.bias_ih_l0"], sd["gru.bias_hh_l0"]
    Wo, bo = sd["out.weight"], sd["out.bias"]   # v x H
    xin = emb @ Wih.T + bih                     # v x 3H: what each character adds
    xq, xs = q8(xin)
    hq, hs = q8(Whh)
    oq, os_ = q8(Wo)
    L = ["#pragma once", "", "#include <stdint.h>", "",
         "// Gaslight's chatter model: a character GRU trained on the game's own",
         "// dialogue (tools/textmodel). Generated by train.py - don't edit.", "",
         "namespace Gaslight {",
         "static const int TM_V = %d, TM_H = %d;" % (v, H),
         "static const char TM_CHARS[] = %s;" % ("{" + ",".join(str(ord(c)) for c in chars) + ",0}"),
         carr("TM_XQ", xq, "int8_t"), carr("TM_XS", xs, "float"),
         carr("TM_HQ", hq, "int8_t"), carr("TM_HS", hs, "float"), carr("TM_HB", bhh, "float"),
         carr("TM_OQ", oq, "int8_t"), carr("TM_OS", os_, "float"), carr("TM_OB", bo, "float"),
         "} // namespace Gaslight", ""]
    open(out, "w", newline="\n").write("\n".join(L))
    print("wrote", out, "vocab", v)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], float(sys.argv[3]) if len(sys.argv) > 3 else 6)
