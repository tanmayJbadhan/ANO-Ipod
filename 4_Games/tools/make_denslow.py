"""Builds Denslow.h: W. W. Denslow's 1900 illustrations for "The Wonderful
Wizard of Oz" (public domain - Denslow died in 1915) as 4-bit greyscale,
sized for the games' half-resolution frame.

usage: python make_denslow.py ../Denslow.h [preview_dir]

Downloads the originals from Wikimedia Commons. With a preview directory it
also saves each crop as a PNG there, to check the framing.
Needs Pillow (pip install pillow).
"""
import io
import os
import sys
import urllib.parse
import urllib.request
from PIL import Image, ImageOps

UA = "JigglypuffConsole/1.0 (https://github.com/tanmayJbadhan/ANO-Ipod)"
BASE = "https://commons.wikimedia.org/wiki/Special:FilePath/"

# name, Commons file, crop box as fractions (left, top, right, bottom), max size in frame px
PICTURES = [
    # Dorothy, the Tin Woodman and the Scarecrow on the road
    ("FRIENDS", "Illustration by W. W. Denslow from The Wonderful Wizard of Oz.jpg",
     (0.07, 0.24, 0.93, 0.93), (100, 124)),
    # Toto before the gates of the Emerald City
    ("CITY", "Emerald City.jpg", (0.0, 0.0, 1.0, 1.0), (196, 122)),
    # the Wizard, found out behind the screen
    ("WIZARD", "Wizard Oz Humbug (cropped).jpg", (0.33, 0.30, 0.64, 0.80), (90, 124)),
]


def fetch(name):
    url = BASE + urllib.parse.quote(name.replace(" ", "_"))
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    return Image.open(io.BytesIO(urllib.request.urlopen(req, timeout=120).read()))


def main(out_path, preview=None):
    out = ["#pragma once", "", "#include <stdint.h>", "",
           "// W. W. Denslow's illustrations for The Wonderful Wizard of Oz (1900),",
           "// public domain, from Wikimedia Commons. 4-bit greyscale, two pixels per",
           "// byte (high nibble first), 0 = ink, 15 = paper. Generated by",
           "// tools/make_denslow.py - don't edit by hand.", ""]
    for name, src, (l, t, r, b), (mw, mh) in PICTURES:
        im = fetch(src).convert("L")
        W, H = im.size
        im = im.crop((int(l * W), int(t * H), int(r * W), int(b * H)))
        im.thumbnail((mw, mh), Image.LANCZOS)
        im = ImageOps.autocontrast(im, cutoff=1)
        if preview:
            im.resize((im.width * 3, im.height * 3), Image.NEAREST).save(os.path.join(preview, name + ".png"))
        w, h = im.size
        nib = [min(15, p * 16 // 256) for p in im.getdata()]
        if len(nib) % 2:
            nib.append(15)
        data = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        out.append(f"// Commons: {src}")
        out.append(f"static const int DENSLOW_{name}_W = {w}, DENSLOW_{name}_H = {h};")
        out.append(f"static const uint8_t DENSLOW_{name}[] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
        out.append("};")
        out.append("")
        print(f"{name}: {w}x{h}, {len(data)} bytes")
    open(out_path, "w", newline="\n").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "Denslow.h", sys.argv[2] if len(sys.argv) > 2 else None)
