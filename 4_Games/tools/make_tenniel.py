"""Builds Tenniel.h: John Tenniel's 1865 illustrations for "Alice's Adventures
in Wonderland" (public domain - Tenniel died in 1914) as 4-bit greyscale,
sized for the games' half-resolution frame.

usage: python make_tenniel.py ../Tenniel.h

Downloads the originals from Wikimedia Commons ("Alice par John Tenniel NN.png").
Needs Pillow (pip install pillow).
"""
import io
import sys
import urllib.request
from PIL import Image, ImageOps

UA = "JigglypuffConsole/1.0 (https://github.com/tanmayJbadhan/ANO-Ipod)"
BASE = "https://commons.wikimedia.org/wiki/Special:FilePath/Alice_par_John_Tenniel_%s.png"

# name, Commons number, crop box as fractions (left, top, right, bottom), max size in frame px
PICTURES = [
    ("RABBIT", "02", (0.08, 0.02, 0.92, 0.80), (100, 124)),   # the White Rabbit and his watch
    ("TEAPARTY", "25", (0.0, 0.0, 1.0, 1.0), (150, 116)),     # the Mad Tea Party
    ("QUEEN", "29", (0.02, 0.24, 0.46, 0.94), (104, 124)),    # the Queen of Hearts, pointing
]


def fetch(num):
    req = urllib.request.Request(BASE % num, headers={"User-Agent": UA})
    return Image.open(io.BytesIO(urllib.request.urlopen(req, timeout=60).read()))


def main(out_path):
    out = ["#pragma once", "", "#include <stdint.h>", "",
           "// John Tenniel's illustrations for Alice's Adventures in Wonderland (1865),",
           "// public domain, from Wikimedia Commons. 4-bit greyscale, two pixels per",
           "// byte (high nibble first), 0 = ink, 15 = paper. Generated by",
           "// tools/make_tenniel.py - don't edit by hand.", ""]
    for name, num, (l, t, r, b), (mw, mh) in PICTURES:
        im = fetch(num).convert("L")
        W, H = im.size
        im = im.crop((int(l * W), int(t * H), int(r * W), int(b * H)))
        im.thumbnail((mw, mh), Image.LANCZOS)
        im = ImageOps.autocontrast(im, cutoff=1)
        w, h = im.size
        px = list(im.getdata())
        nib = [min(15, p * 16 // 256) for p in px]
        if len(nib) % 2:
            nib.append(15)
        data = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        out.append(f"// Commons: Alice par John Tenniel {num}.png")
        out.append(f"static const int TENNIEL_{name}_W = {w}, TENNIEL_{name}_H = {h};")
        out.append(f"static const uint8_t TENNIEL_{name}[] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
        out.append("};")
        out.append("")
        print(f"{name}: {w}x{h}, {len(data)} bytes")
    open(out_path, "w", newline="\n").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "Tenniel.h")
