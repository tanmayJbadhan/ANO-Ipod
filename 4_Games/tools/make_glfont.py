"""Builds Gaslight/GLFont.h: anti-aliased proportional fonts for Gaslight & Griffins.

usage: python make_glfont.py ../Gaslight/GLFont.h

Renders printable ASCII from DejaVu Serif (Bitstream Vera licence: free to
embed and modify; the copy bundled with matplotlib is used). Each glyph is
4-bit coverage, two pixels per byte (high nibble first), rows packed to whole
bytes. Every font has one fixed line height; glyphs are drawn at the top of it.
"""
import os
import sys
import matplotlib
from PIL import Image, ImageDraw, ImageFont

TTF = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")

# name, file, pixel size
FONTS = [
    ("BODY", "DejaVuSerif.ttf", 22),
    ("BOLD", "DejaVuSerif-Bold.ttf", 22),
    ("TITLE", "DejaVuSerif-Bold.ttf", 34),
    ("SMALL", "DejaVuSans.ttf", 18),
]


def build(name, file, size):
    font = ImageFont.truetype(os.path.join(TTF, file), size)
    asc, desc = font.getmetrics()
    lineh = asc + desc
    glyphs, data = [], bytearray()
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        l, t, r, b = font.getbbox(ch)
        w = max(0, r - l)
        im = Image.new("L", (max(1, w), lineh), 0)
        ImageDraw.Draw(im).text((-l, 0), ch, font=font, fill=255)
        stride = (w + 1) // 2
        off = len(data)
        for y in range(lineh):
            row = [im.getpixel((x, y)) if x < w else 0 for x in range(stride * 2)]
            for x in range(0, stride * 2, 2):
                data.append(((row[x] * 15 + 127) // 255) << 4 | ((row[x + 1] * 15 + 127) // 255))
        glyphs.append((off, w, adv, l))
    return lineh, asc, glyphs, data


def main(out):
    lines = ["#pragma once", "", "#include <stdint.h>", "",
             "// Anti-aliased fonts for Gaslight & Griffins, rendered from DejaVu Serif/Sans",
             "// (Bitstream Vera licence). Generated by tools/make_glfont.py - don't edit.",
             "// Glyphs for ASCII 32..126: {data offset, width, advance, x offset}; each",
             "// glyph is `height` rows of ceil(width/2) bytes, 4-bit coverage, high nibble first.",
             "",
             "namespace Gaslight {",
             "struct GlyphInfo { uint32_t off; uint8_t w, adv; int8_t xoff; };",
             "struct FontInfo { uint8_t height, ascent; const GlyphInfo *g; const uint8_t *data; };",
             ""]
    for name, file, size in FONTS:
        h, asc, glyphs, data = build(name, file, size)
        lines.append(f"static const GlyphInfo FONT_{name}_G[95] = {{")
        for off, w, adv, l in glyphs:
            lines.append(f"  {{{off}, {w}, {adv}, {l}}},")
        lines.append("};")
        lines.append(f"static const uint8_t FONT_{name}_D[{len(data)}] = {{")
        for i in range(0, len(data), 32):
            lines.append("  " + ",".join(str(v) for v in data[i:i + 32]) + ",")
        lines.append("};")
        lines.append(f"static const FontInfo FONT_{name} = {{{h}, {asc}, FONT_{name}_G, FONT_{name}_D}};")
        lines.append("")
        print(f"{name}: height {h}, {len(data)} bytes")
    lines.append("} // namespace Gaslight")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "../Gaslight/GLFont.h")
